let LANG = (() => {
  try {
    const saved = localStorage.getItem("lt-lang");
    if (saved === "nl" || saved === "en") return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || "en").toLowerCase().startsWith("nl") ? "nl" : "en";
})();

function t(key, vars = {}) {
  const s = (TEXTS[LANG] && TEXTS[LANG][key]) ?? TEXTS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

function setLang(lang) {
  LANG = lang;
  try { localStorage.setItem("lt-lang", lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
}
